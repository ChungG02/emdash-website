const messages: Record<UiLocale, UiMessages> = { vi, en, zh };

export type UiMessageKey = keyof typeof vi;

export function isUiLocale(value: unknown): value is UiLocale {
  return (
    typeof value === "string" &&
    supportedUiLocales.includes(value as UiLocale)
  );
}

export function getUiLocale(cookies: CookieReader): UiLocale {
  const locale = cookies.get(UI_LOCALE_COOKIE)?.value;
  return isUiLocale(locale) ? locale : "vi";
}

export function useTranslations(locale: UiLocale) {
  return (
    key: UiMessageKey,
    variables: Record<string, string | number> = {},
  ): string => {
    let message: string = messages[locale][key] ?? messages.vi[key];

    for (const [name, value] of Object.entries(variables)) {
      message = message.replaceAll(`{${name}}`, String(value));
    }

    return message;
  };
}
